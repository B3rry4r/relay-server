// File: src/relay-server/web-skeleton.ts
//
// GEN_PHASE 3 (Skeleton) for the web targets — the React (Vite + react-router) and
// Next.js (App Router) counterpart of canonicalize.ts → generateFlutterSkeleton.
//
// Every web pass (7a–7h) resolves screens, routes, placeholders and the theme from
// a contract: a `ROUTES` table, a react-router `<Routes>` (or the Next app dir), a
// `// canonicalId: <id> route: <route>` header on every screen, `PlaceholderScreen`
// for an unbuilt slot, `showModal_<core>()` + `modalController` for folded modals,
// and an `AppTheme` token object. Until this module existed nothing in the pipeline
// emitted any of it — the build agent was told to "create a central route table" in
// whatever shape it liked, and the passes worked only when an agent happened to
// invent this one (parity audit PG-02). This emits the contract deterministically,
// BEFORE screen 1 builds, from canonical.json:
//
//   react (Vite, CONTRACTS §5: pipeline files under src/)
//     src/router/routes.ts            ROUTES table + ENTRY_ROUTE (write-locked)
//     src/App.tsx                     <BrowserRouter><Routes> — one <Route> per canonical
//                                     screen, the tab cluster nested under <AppShell/>,
//                                     one verify route per frame at /_preview/<frame>
//     src/main.tsx                    entry → App + theme.css (only when missing/boilerplate)
//     src/shell/AppShell.tsx          the ONE shared tab bar (tab cluster only)
//     src/screens/<Class>.tsx         a header-stamped stub per canonical screen
//     src/modal/*                     modalController + ModalHost + a presenter stub per
//                                     folded modal (`showModal_<core>()`, fixed name)
//     src/_preview/<X>Preview.tsx     modal verify harness (auto-presents the modal)
//     src/components/PlaceholderScreen.tsx, src/theme/theme.{ts,css} (stubs)
//
//   next (App Router, CONTRACTS §5: pipeline files beside the app dir's parent `<root>`)
//     <root>/lib/routes.ts            ROUTES table + ENTRY_ROUTE
//     <root>/app/<route>/page.tsx     a header-stamped stub page per canonical screen
//                                     (the header sits ABOVE 'use client'); the tab
//                                     cluster lives in the `(tabs)` route group whose
//                                     layout renders <AppShell>
//     <root>/app/%5Fpreview/<frame>/page.tsx   verify routes — `/_preview/<frame>`. A
//                                     folder named `_preview` is a PRIVATE folder the
//                                     App Router never routes; `%5F` is the escape.
//     <root>/app/layout.tsx, app/page.tsx      root layout (theme.css + ModalHost) and a
//                                     redirect to the entry route (missing/boilerplate only)
//     <root>/components/*, <root>/lib/modal/modalController.ts, <root>/lib/theme/*
//
// An EMPTY project also gets the minimal toolchain files (package.json, tsconfig,
// vite/next config, index.html) so the skeleton builds on its own; an existing
// scaffold keeps its own and only gains what the contract needs (react-router-dom
// on react; `output: 'export'` on next — the verify harness serves a static export).
//
// Additive + idempotent, exactly like the Flutter skeleton: a built screen / modal
// file is NEVER clobbered; the write-locked contract files (route table, router,
// shell, previews) are regenerated only when missing, generated by us, or the
// framework's own untouched boilerplate — a hand-written file is left alone and
// reported in `kept`. Running it twice writes nothing the second time.
// =============================================================================

