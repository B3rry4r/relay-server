const MODAL_CONTROLLER = `// ${WEB_SKELETON_MARKER} — modal controller (write-locked API surface).
// Folded modals are presented OVER their base screen, never routed to: a presenter
// \`showModal_<id>()\` calls modalController.open('<modalId>', <Content />) and the
// ModalHost mounted once at the app root renders it above a scrim.
// The controller REMEMBERS the open modal: a presenter called from a screen's (or the
// verify preview's) mount effect runs before the root ModalHost's own effect has
// subscribed, so a late subscriber must still receive what is already open.
import type { ReactNode } from 'react';

type Listener = (id: string | null, node: ReactNode | null) => void;
const listeners = new Set<Listener>();
let current: { id: string; node: ReactNode } | null = null;

export const modalController = {
  open(id: string, node: ReactNode): void {
    current = { id, node };
    listeners.forEach((l) => l(id, node));
  },
  close(): void {
    current = null;
    listeners.forEach((l) => l(null, null));
  },
  subscribe(l: Listener): () => void {
    listeners.add(l);
    if (current) l(current.id, current.node);
    return () => { listeners.delete(l); };
  },
};
`;

function modalHostSource(controllerSpec: string, client: boolean): string {
  return `${client ? "'use client';\n\n" : ''}// ${WEB_SKELETON_MARKER} — the ONE modal host, mounted once at the app root.
// Renders whatever modalController.open(…) presents above a scrim; a tap on the
// scrim closes it. The modal content positions itself (a bottom sheet anchors to
// bottom: 0, a dialog centers itself).
import { useEffect, useState } from 'react';
import type { ReactNode } from 'react';
import { modalController } from '${controllerSpec}';

export function ModalHost() {
  const [node, setNode] = useState<ReactNode | null>(null);
  useEffect(() => modalController.subscribe((_id, next) => setNode(next)), []);
  if (!node) return null;
  return (
    <div style={{ position: 'fixed', inset: 0, zIndex: 1000 }}>
      <div
        aria-hidden="true"
        onClick={() => modalController.close()}
        style={{ position: 'absolute', inset: 0, background: 'rgba(0, 0, 0, 0.45)' }}
      />
      {node}
    </div>
  );
}
`;
}

