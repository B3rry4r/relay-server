// ── plan (shared by react + next) ─────────────────────────────────────────────

function planModals(canonical: Canonical, opts: WebSkeletonOptions | undefined, fileFor: (component: string) => string): PlannedModal[] {
  const used = new Set<string>();
  const out: PlannedModal[] = [];
  for (const c of canonical.screens) {
    for (const m of c.modals) {
      const frameName = opts?.frameNames?.[m.frameId] ?? '';
      const words = meaningfulTokens(frameName).filter(w => !/^(modal|sheet|dialog|popup|overlay)$/.test(w));
      let base = words.length ? `${pascalWords(words)}Modal` : `Modal${idToken(m.id).replace(/_/g, '')}`;
      if (!/^[A-Z]/.test(base)) base = `M${base}`;
      let name = base;
      for (let n = 2; used.has(name); n++) name = `${base}${n}`;
      used.add(name);
      out.push({
        modalId: m.id, frameId: m.frameId, baseCanonicalId: m.baseCanonicalId ?? c.canonicalId,
        component: name, presenter: presenterName(m.id), file: fileFor(name),
        title: frameName ? humanTitle(frameName) : m.id,
      });
    }
  }
  return out;
}

function stateType(s: PlannedScreen): string {
  return s.states.map(lit).join(' | ') || lit('default');
}

function screenHeader(s: PlannedScreen): string {
  const c = s.c;
  return `// canonicalId: ${c.canonicalId} route: ${s.route}
// ${WEB_SKELETON_MARKER} — write-locked route slot for canonical screen.
// states: ${s.states.join(', ') || 'default'}${c.modals.length ? `\n// modals: ${c.modals.map(m => m.id).join(', ')}` : ''}
// The per-screen build REPLACES the body of ${s.className} with the real UI (keep this header).
`;
}

