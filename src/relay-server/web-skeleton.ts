// ── the writer (additive, idempotent, reports what it did) ───────────────────

class Writer {
  files: string[] = [];
  kept: string[] = [];
  warnings: string[] = [];
  constructor(private root: string) {}
  abs(rel: string): string { return path.join(this.root, rel); }
  read(rel: string): string | null { try { return fsSync.readFileSync(this.abs(rel), 'utf8'); } catch { return null; } }
  exists(rel: string): boolean { return fsSync.existsSync(this.abs(rel)); }
  private async put(rel: string, content: string): Promise<void> {
    if (this.read(rel) === content) return;           // idempotent: no churn
    await fs.mkdir(path.dirname(this.abs(rel)), { recursive: true });
    await fs.writeFile(this.abs(rel), content, 'utf8');
    this.files.push(posix(rel));
  }
  /** A stub the build fills in: written only when absent (never clobber a built file). */
  async stub(rel: string, content: string): Promise<void> {
    if (this.exists(rel)) return;
    await this.put(rel, content);
  }
  /** A write-locked contract file: (re)generated when absent, ours, or `replaceable`
   *  boilerplate; a hand-written file is kept and reported. Returns true when the
   *  file on disk is now ours. */
  async locked(rel: string, content: string, replaceable?: (src: string) => boolean): Promise<boolean> {
    const cur = this.read(rel);
    if (cur === null || ours(cur) || (replaceable && replaceable(cur))) { await this.put(rel, content); return true; }
    this.kept.push(posix(rel));
    return false;
  }
}

