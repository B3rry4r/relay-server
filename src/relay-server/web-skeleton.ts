export interface WebNukeResult {
  /** project-relative files removed. */
  removed: string[];
  /** project-relative directories left empty by the removal and pruned. */
  prunedDirs: string[];
  /** unmarked (hand-authored) files kept, which still import a removed file. */
  keptImporting: string[];
}

/**
 * The web half of a restart's clean slate (PG-34): remove the generated app surface
 * so the rebuild does not mix the previous build's screens, previews and routes
 * with the new ones — and NEVER a hand-authored file. The caller has committed a
 * git checkpoint first (the same data-safety contract as the flutter `lib/` nuke).
 *
 * Removed, across every source root the shared resolver walks (src/, app/,
 * components/, lib/, pages/):
 *   • every file carrying a `// canonicalId: <id> route: <route>` header — a
 *     generated screen, built or still the skeleton stub;
 *   • every file carrying a pipeline marker (`GENERATED SKELETON` router / route
 *     table / shell / modal stubs, the design-system theme, the asset pass's
 *     resources module, verify preview entries);
 *   • the verify preview routes: Next `<app>/%5Fpreview/**` (and a stray
 *     `<app>/_preview/**`), react `src/_preview/**`.
 * Kept: package.json, tsconfig, vite/next config, index.html, public/ (localized
 * assets are expensive and the asset pass re-emits the resources module), and any
 * unmarked file — reported in `keptImporting` when it imports something removed.
 */
async function listDirFiles(dir: string, acc: string[] = []): Promise<string[]> {
  let entries: fsSync.Dirent[] = [];
  try { entries = await fs.readdir(dir, { withFileTypes: true }); } catch { return acc; }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) await listDirFiles(p, acc); else acc.push(p);
  }
  return acc;
}

export async function nukeWebAppSurface(projectRoot: string): Promise<WebNukeResult> {
  const out: WebNukeResult = { removed: [], prunedDirs: [], keptImporting: [] };
  const ix = await loadWebApp(projectRoot);
  if (!ix) return out;
  const rel = (p: string): string => posix(path.relative(projectRoot, p));
  const previewDirs = [
    ...(ix.appDir ? [path.join(ix.appDir, '%5Fpreview'), path.join(ix.appDir, '_preview')] : []),
    path.join(projectRoot, 'src', '_preview'),
  ];
  const inPreviewDir = (f: string): boolean => previewDirs.some((d) => f.startsWith(d + path.sep));
  // The resolver's walker never enters a preview dir (verify harness, not the app),
  // so the preview routes are removed wholesale.
  for (const d of previewDirs) {
    if (!isDir(d)) continue;
    const inside = await listDirFiles(d);
    await fs.rm(d, { recursive: true, force: true });
    out.removed.push(...inside.map(rel));
    out.prunedDirs.push(rel(d));
  }
  const files = await listWebSources(ix);
  const removed = new Set<string>();
  const kept: Array<{ file: string; src: string }> = [];
  for (const f of files) {
    const src = await fs.readFile(f, 'utf8').catch(() => '');
    const generated = inPreviewDir(f) || !!readHeader(src) || PIPELINE_MARKERS.some((m) => src.includes(m));
    if (!generated) { kept.push({ file: f, src }); continue; }
    await fs.rm(f, { force: true });
    removed.add(f);
    out.removed.push(rel(f));
  }
  // theme.css next to a removed theme module is part of the same generated pair.
  for (const f of files) {
    if (!removed.has(f) || !/theme\.ts$/.test(f)) continue;
    const css = f.replace(/\.ts$/, '.css');
    const cssSrc = await fs.readFile(css, 'utf8').catch(() => null);
    if (cssSrc != null && cssSrc.includes('GENERATED')) { await fs.rm(css, { force: true }); out.removed.push(rel(css)); }
  }
  // Prune directories the removal emptied (app/10-3/, app/%5Fpreview/10-3/ …), never a root.
  const roots = new Set(ix.sourceRoots.map((r) => path.resolve(r)));
  const dirs = [...new Set([...removed].map((f) => path.dirname(f)))].sort((a, b) => b.length - a.length);
  for (let d of dirs) {
    while (!roots.has(path.resolve(d)) && d.startsWith(projectRoot + path.sep)) {
      let entries: string[] = [];
      try { entries = await fs.readdir(d); } catch { break; }
      if (entries.length) break;
      await fs.rmdir(d).catch(() => undefined);
      out.prunedDirs.push(rel(d));
      d = path.dirname(d);
    }
  }
  // A kept (hand-authored) file that still imports a removed one is reported, not
  // touched: the rebuild's skeleton keeps it as hand-written, so a human must look.
  for (const k of kept) {
    const specs = [...k.src.matchAll(/from\s+['"](\.{1,2}\/[^'"]+)['"]/g)].map((m) => path.resolve(path.dirname(k.file), m[1]));
    if (specs.some((b) => ['', '.tsx', '.ts', '.jsx', '.js', '/index.tsx', '/index.ts'].some((ext) => removed.has(b + ext)))) out.keptImporting.push(rel(k.file));
  }
  return out;
}

/** A single-quoted TS string literal (the house style of the generated code). */
const lit = (s: string): string => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
/** A JSX attribute value: `"text"` when plain, `{'text'}` otherwise. */
const jsxAttr = (s: string): string => (/^[^"{}<>\\\n]*$/.test(s) ? `"${s}"` : `{${lit(s)}}`);

/** "loginScreen" → "Login", "283:1967" → "283:1967" (machine names stay recognisable). */
function humanTitle(name: string): string {
  const words = meaningfulTokens(name);
  if (!words.length) return tokenizeName(name).join(' ') || name;
  return words.map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

const pascalWords = (words: string[]): string =>
  words.map(w => (w ? w.charAt(0).toUpperCase() + w.slice(1) : w)).join('');

const idToken = (id: string): string => String(id).replace(/^[cm]_/, '').replace(/[^a-zA-Z0-9]+/g, '_').toLowerCase();

/** The fixed presenter name (must equal design-system.modalPresenterName). */
const presenterName = (modalId: string): string => `showModal_${idToken(modalId)}`;

